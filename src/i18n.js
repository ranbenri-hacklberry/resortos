function readStoredLanguage() {
  try {
    return (typeof localStorage !== 'undefined' && localStorage.getItem('hotelos-lang')) || 'he';
  } catch (_) {
    return 'he';
  }
}

const savedLng = readStoredLanguage();

function applyDocumentLanguage(lng) {
  const lang = (lng || 'he').split('-')[0];
  if (typeof document === 'undefined') return;
  document.documentElement.setAttribute('dir', lang === 'he' || lang === 'ar' ? 'rtl' : 'ltr');
  document.documentElement.setAttribute('lang', lang);
}

i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: savedLng,
    fallbackLng: 'he',
    interpolation: {
      escapeValue: false
    }
  });

applyDocumentLanguage(savedLng);

export function persistLanguage(lng) {
  const lang = (lng || 'he').split('-')[0];
  try {
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('hotelos-lang', lang);
    }
  } catch (_) {}
  applyDocumentLanguage(lang);
}

export default i18n;
